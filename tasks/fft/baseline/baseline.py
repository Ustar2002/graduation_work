"""fft 성능 기준선: NumPy ``np.fft.fft`` (라이브러리 위임, 단일 스레드 pocketfft). 하네스가 python 백엔드 커널로 똑같이 측정한다.

교차 저장된 float32 버퍼를 complex64 뷰로 보고(복사 없음) 결과를 ``out`` 의 complex64 뷰에 받는다(``out=`` 은 NumPy 2.0 부터).
결과 dtype 은 단정밀도(complex64)로 남지만 **NumPy 내부에서는 배정밀도로 계산된다**(numpy 2.3.5; 2026-11-21 실측, 2026-11-22 재확인).
정규화 계수가 Python ``int`` 1 로 넘어가 gufunc(루프 순서 ``Dd->D, Ff->F, Gg->G``)의 타입 해석이 첫 루프 ``Dd->D`` 를 고르고,
입력·출력 전체가 complex128 로 변환됐다가 complex64 로 되돌아온다. 근거:

- 네 형태 모두 결과가 "complex128 로 계산해 complex64 로 내린 값"과 비트 단위로 같다(n = 2^22 에서 8,388,608 개 중 0 개 다름).
  단정밀도 루프(``Ff->F``)의 결과와는 대부분의 원소가 다르다(7,159,770 개).
- 호출 중 NumPy 가 잡는 임시 메모리가 134 MB(= n 원소 complex128 두 개)다. 단정밀도 루프는 0 MB.
- 호출 시간이 complex128 변환과 같거나 더 길다(n = 2^22, 개발 머신에서 번갈아 9회씩 잰 최솟값: 이 호출 190 ms,
  complex128 변환 183 ms, 단정밀도 루프 101 ms; 다른 작업이 도는 중에는 468–552 ms / 342–446 ms / 176–243 ms).

따라서 오차는 float32 반올림뿐이고(허용오차의 4e-5 배), 같은 라이브러리의 단정밀도 루프보다 느리다: ``norm="forward"`` 로
``Ff->F`` 루프를 타게 한 뒤 n 을 곱하면(n 이 2의 거듭제곱이라 정확하다 — 결과가 단정밀도 루프와 비트 단위로 같다) 104 ms 로
약 1.8배 빠르다. 기준선은 "라이브러리를 평범하게 부른 값"이므로 그대로 둔다(docs/decisions.md 의 fft 항목).
워커가 임포트해 fft 를 호출하므로 임포트 시 실행되는 코드를 두지 않는다.
"""
import numpy as np


def fft(x, out, n):
    np.fft.fft(x.view(np.complex64), out=out.view(np.complex64))
